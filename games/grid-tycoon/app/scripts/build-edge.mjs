// Bundles the engine for the grid-tycoon edge function.
//
//   node scripts/build-edge.mjs           -> supabase/functions/grid-tycoon/engine.js
//   node scripts/build-edge.mjs --check   -> also typechecks the function (index.ts + rooms.ts) with a Deno shim
//
// The function runs the exact engine the browser runs: src/engine/index.ts with config/balance.json
// inlined, as one self-contained ES module (no imports), so it can be uploaded as a plain file.

import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { readFileSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const fnDir = resolve(appDir, '../supabase/functions/grid-tycoon')
const outfile = join(fnDir, 'engine.js')

await build({
  entryPoints: [join(appDir, 'src/engine/index.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  loader: { '.json': 'json' },
  legalComments: 'none',
  charset: 'utf8',
  banner: { js: '// Generated by app/scripts/build-edge.mjs from app/src/engine. Do not edit: run `npm run build:edge`.' },
  logLevel: 'warning',
})

const code = readFileSync(outfile, 'utf8')
if (/^\s*import\s/m.test(code) || /\brequire\(/.test(code)) {
  console.error('build-edge: engine.js must be self-contained but it still imports something')
  process.exit(1)
}
for (const name of ['createGame', 'resolveRound', 'validateDecision', 'defaultDecision', 'botDecision', 'BOT_NAMES', 'defaultConfig']) {
  if (!new RegExp(`\\b${name}\\b`).test(code.slice(code.lastIndexOf('export {')))) {
    console.error(`build-edge: engine.js does not export ${name}`)
    process.exit(1)
  }
}
console.log(`build-edge: wrote ${relative(appDir, outfile)} (${(statSync(outfile).size / 1024).toFixed(1)} KB)`)

if (process.argv.includes('--check')) {
  const tsc = join(appDir, 'node_modules/typescript/bin/tsc')
  try {
    execFileSync(process.execPath, [tsc, '-p', resolve(appDir, '../supabase/tsconfig.check.json')], { stdio: 'inherit' })
    console.log('build-edge: function typechecks (Deno shim)')
  } catch {
    process.exit(1)
  }
}

console.log('build-edge: deploy files index.ts, rooms.ts, engine.js from supabase/functions/grid-tycoon (see supabase/README.md)')
