// Balance pass: 20 bot-only games (seeds 1..20, 4 bots each), summarized in .sim/balance.md.
// Usage: npm run balance

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createSoloGame, defaultConfig, POOLS, rankCompanies, resolveRound, type BotStyle, type GameState, type PoolId } from '../src/engine'
import { playGame, SIM_STYLES } from './sim'

const SEEDS = Array.from({ length: 20 }, (_, i) => i + 1)
const STYLES: BotStyle[] = ['volta', 'nimbus', 'hashfield']

interface StyleStats {
  prices: number[]
  wins: number
  bankrupt: number
  forcedSaleRounds: number
  idle: number[]
  revenue: Record<PoolId, number>
  loansTaken: number
  sharesIssued: number
  sharesBought: number
  finalTreasury: number[]
  finalDebt: number[]
  finalShares: number[]
  finalMarketCap: number[]
  upgrades: number
  bigBuilds: number
  smallBuilds: number
}

const empty = (): StyleStats => ({
  prices: [],
  wins: 0,
  bankrupt: 0,
  forcedSaleRounds: 0,
  idle: [],
  revenue: { citizens: 0, otherDc: 0, cloud: 0, btc: 0, ai: 0 },
  loansTaken: 0,
  sharesIssued: 0,
  sharesBought: 0,
  finalTreasury: [],
  finalDebt: [],
  finalShares: [],
  finalMarketCap: [],
  upgrades: 0,
  bigBuilds: 0,
  smallBuilds: 0,
})

const mean = (xs: number[]): number => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0)
const fmt = (x: number, d = 2): string => x.toFixed(d)
const pct = (x: number): string => `${(x * 100).toFixed(1)}%`

function main(): void {
  const stats = new Map<BotStyle, StyleStats>(STYLES.map((s) => [s, empty()]))
  const games: { seed: number; ranking: string; spread: number; unserved: Record<PoolId, number> }[] = []
  const poolTotals = { demand: { citizens: 0, otherDc: 0, cloud: 0, btc: 0, ai: 0 }, used: { citizens: 0, otherDc: 0, cloud: 0, btc: 0, ai: 0 } }
  let nanFound = false
  const t0 = performance.now()
  let rounds = 0

  for (const seed of SEEDS) {
    const state: GameState = playGame(seed, SIM_STYLES, () => rounds++)
    if (JSON.stringify(state).includes('null') && hasNaN(state)) nanFound = true
    const ranking = rankCompanies(state)
    const prices = state.companies.map((c) => c.sharePrice)
    for (const c of state.companies) {
      const s = stats.get(c.bot!)!
      s.prices.push(c.sharePrice)
      if (ranking[0] === c.id) s.wins++
      if (c.bankrupt) s.bankrupt++
      for (const r of c.history) {
        s.idle.push(r.idle)
        for (const p of POOLS) s.revenue[p] += r.revenueByPool[p]
        if (r.finance.forcedSold.length > 0 || r.finance.forcedSharesIssued > 0) s.forcedSaleRounds++
        if (r.finance.loanTaken > 0) s.loansTaken++
        s.sharesIssued += r.finance.sharesIssued
        s.sharesBought += r.finance.sharesBought
      }
      s.finalTreasury.push(c.treasury)
      s.finalDebt.push(c.loans.reduce((a, l) => a + l.principal, 0))
      s.finalShares.push(c.shares)
      s.finalMarketCap.push(c.marketCap)
      for (const b of c.buildings) {
        if (b.builtRound === 0 && b.size === 'small') continue
        if (b.pricePaid > defaultConfig.buildings[b.kind].big.cost) s.upgrades++
        else if (b.size === 'big') s.bigBuilds++
        else s.smallBuilds++
      }
    }
    const unserved = { citizens: 0, otherDc: 0, cloud: 0, btc: 0, ai: 0 }
    for (const h of state.history) {
      for (const p of POOLS) {
        poolTotals.demand[p] += h.pools[p].demand
        poolTotals.used[p] += h.pools[p].used
        unserved[p] += h.pools[p].demand - h.pools[p].used
      }
    }
    games.push({
      seed,
      ranking: ranking.map((id) => `${id} ${state.companies.find((c) => c.id === id)!.sharePrice.toFixed(0)}`).join(', '),
      spread: Math.max(...prices) / Math.max(0.01, Math.min(...prices)),
      unserved,
    })
  }
  const ms = performance.now() - t0

  const lines: string[] = []
  lines.push('# Grid Tycoon balance pass', '')
  lines.push(`20 bot-only games, seeds 1..20, bots ${SIM_STYLES.join(', ')}. Generated by \`npm run balance\`. ${rounds} rounds resolved in ${fmt(ms, 0)} ms (${fmt(ms / rounds, 3)} ms per round, bot decisions included).`, '')
  lines.push('## Final share price per style', '')
  lines.push('| Style | Games | Mean | Min | Max | Wins | Bankrupt | Rounds with forced sales | Avg idle | Final treasury (mean) | Final debt (mean) |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const style of STYLES) {
    const s = stats.get(style)!
    lines.push(
      `| ${style} | ${s.prices.length} | ${fmt(mean(s.prices))} | ${fmt(Math.min(...s.prices))} | ${fmt(Math.max(...s.prices))} | ${s.wins} | ${s.bankrupt} | ${s.forcedSaleRounds} | ${pct(mean(s.idle))} | ${fmt(mean(s.finalTreasury), 0)} | ${fmt(mean(s.finalDebt), 0)} |`,
    )
  }
  lines.push('', '## Revenue mix per pool (share of each style’s revenue over all games)', '')
  lines.push(`| Style | ${POOLS.join(' | ')} |`)
  lines.push(`| --- | ${POOLS.map(() => '---').join(' | ')} |`)
  for (const style of STYLES) {
    const s = stats.get(style)!
    const total = POOLS.reduce((a, p) => a + s.revenue[p], 0)
    lines.push(`| ${style} | ${POOLS.map((p) => pct(s.revenue[p] / total)).join(' | ')} |`)
  }
  lines.push('', '## Habits (totals over all games of the style)', '')
  lines.push('| Style | Rounds with a new loan | Shares issued | Shares bought back | Final shares (mean) | Small builds | Big builds | Upgrades |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const style of STYLES) {
    const s = stats.get(style)!
    lines.push(`| ${style} | ${s.loansTaken} | ${s.sharesIssued} | ${s.sharesBought} | ${fmt(mean(s.finalShares), 1)} | ${s.smallBuilds} | ${s.bigBuilds} | ${s.upgrades} |`)
  }
  lines.push('', '## Pools: share of demand served (all games, all rounds)', '')
  lines.push(`| ${POOLS.join(' | ')} |`, `| ${POOLS.map(() => '---').join(' | ')} |`)
  lines.push(`| ${POOLS.map((p) => pct(poolTotals.used[p] / poolTotals.demand[p])).join(' | ')} |`)
  lines.push('', '## Games', '', '| Seed | Final ranking (price) | Top / bottom |', '| --- | --- | --- |')
  for (const g of games) lines.push(`| ${g.seed} | ${g.ranking} | ${fmt(g.spread, 1)}x |`)

  lines.push('', '## Solo: what the player faces (seeds 1..20, the 3 bots of a solo game)', '')
  lines.push('| You play | You (mean) | Your wins | volta | nimbus | hashfield |', '| --- | --- | --- | --- | --- | --- |')
  for (const as of [null, 'volta', 'hashfield', 'nimbus'] as const) {
    const solo = soloGames(as)
    const m = (id: string): string => fmt(mean(solo.map((g) => g.companies.find((c) => c.id === id)!.sharePrice)))
    const wins = solo.filter((g) => rankCompanies(g)[0] === 'you').length
    lines.push(`| ${as ? `a ${as} copy` : 'the default decision (never decides)'} | ${m('you')} | ${wins} | ${m('volta')} | ${m('nimbus')} | ${m('hashfield')} |`)
  }

  lines.push('', '## Read', '')
  for (const line of read(stats, poolTotals, games, nanFound)) lines.push(`- ${line}`)
  lines.push('')

  const here = dirname(fileURLToPath(import.meta.url))
  const out = resolve(here, '../.sim/balance.md')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, lines.join('\n'))
  console.log(lines.join('\n'))
  console.log(`\nWrote ${out}`)
}

/** Solo games where the player never decides (null) or plays the given bot style. */
function soloGames(as: BotStyle | null): GameState[] {
  return SEEDS.map((seed) => {
    let s = createSoloGame({ seed, playerName: 'You' }, defaultConfig)
    if (as) s = { ...s, companies: s.companies.map((c) => (c.id === 'you' ? { ...c, isBot: true, bot: as } : c)) }
    while (!s.finished) s = resolveRound(s, {}, defaultConfig)
    return s
  })
}

function hasNaN(x: unknown): boolean {
  if (typeof x === 'number') return !Number.isFinite(x)
  if (Array.isArray(x)) return x.some(hasNaN)
  if (x && typeof x === 'object') return Object.values(x).some(hasNaN)
  return false
}

function read(
  stats: Map<BotStyle, StyleStats>,
  pools: { demand: Record<PoolId, number>; used: Record<PoolId, number> },
  games: { spread: number }[],
  nanFound: boolean,
): string[] {
  const out: string[] = []
  const by = STYLES.map((s) => ({ s, m: mean(stats.get(s)!.prices), st: stats.get(s)! }))
  by.sort((a, b) => b.m - a.m)
  out.push(`Strongest style on average: ${by[0].s} (${fmt(by[0].m)}), weakest: ${by.at(-1)!.s} (${fmt(by.at(-1)!.m)}); ratio ${fmt(by[0].m / by.at(-1)!.m, 1)}x.`)
  const bankrupt = by.reduce((a, x) => a + x.st.bankrupt, 0)
  out.push(bankrupt === 0 ? 'No bankruptcies in 80 bot companies.' : `${bankrupt} bankruptcies: check the debt habits of the styles above.`)
  const forced = by.reduce((a, x) => a + x.st.forcedSaleRounds, 0)
  out.push(forced === 0 ? 'No losing rounds (forced sales).' : `${forced} losing rounds with forced sales.`)
  for (const x of by) {
    const idle = mean(x.st.idle)
    if (idle > 0.25) out.push(`${x.s} runs ${pct(idle)} idle on average, above the 25% bot target: it overbuilds or misroutes.`)
  }
  const spreads = games.map((g) => g.spread)
  out.push(`Top-to-bottom price ratio per game: mean ${fmt(mean(spreads), 1)}x, min ${fmt(Math.min(...spreads), 1)}x, max ${fmt(Math.max(...spreads), 1)}x.`)
  const winners = by.filter((x) => x.st.wins > 0).map((x) => `${x.s} ${x.st.wins}`)
  out.push(`Wins: ${winners.join(', ')}.`)
  for (const p of POOLS) {
    const served = pools.used[p] / pools.demand[p]
    if (served < 0.85) out.push(`The ${p} pool is only ${pct(served)} served: demand there goes begging, so either its margin is too thin for bots or they under-read it.`)
  }
  for (const x of by) {
    const cashToCap = mean(x.st.finalTreasury) / Math.max(1, mean(x.st.finalMarketCap))
    if (cashToCap > 0.3) {
      out.push(
        `${x.s} ends with a treasury worth ${pct(cashToCap)} of its market cap. Treasury sits outside market cap, so that cash earns nothing for the price: ` +
          (x.st.sharesBought === 0 ? 'this style never buys back, and a player who does (or keeps building) beats it.' : 'buybacks are capped, see below.'),
      )
    }
  }
  const minShares = Math.min(...by.flatMap((x) => x.st.finalShares))
  const capAt = Math.ceil(1 / defaultConfig.shares.maxChangePerRound) - 1
  if (minShares <= capAt) {
    out.push(
      `Rule note: with ${defaultConfig.start.shares} start shares and a ${pct(defaultConfig.shares.maxChangePerRound)} cap rounded down to whole shares, buybacks stall at ${capAt} shares ` +
        `(floor(${defaultConfig.shares.maxChangePerRound} x ${capAt}) = 0); bots reached ${minShares}. Late buybacks multiply the price by up to ${fmt(defaultConfig.start.shares / capAt, 1)}x and then stop, and one issued share dilutes by ${pct(1 / (defaultConfig.start.shares + 1))}. A larger start.shares (100 or 1000) would make issue and buyback smooth.`,
    )
  }
  const upgrades = by.reduce((a, x) => a + x.st.upgrades, 0)
  if (upgrades === 0) {
    const p = defaultConfig.buildings.plant
    out.push(
      `Rule note: no bot ever upgrades. Small + upgrade costs ${p.small.cost + p.upgrade.cost} for ${p.big.mw} MW against ${p.big.cost} for a new big plant, lots are unlimited and maintenance follows price paid, so an upgrade is never the better buy; it only makes sense if lots ever become scarce.`,
    )
  }
  const top = by[0]
  const topAi = top.st.revenue.ai / POOLS.reduce((a, p) => a + top.st.revenue[p], 0)
  if (top.st.wins >= games.length * 0.8) {
    out.push(
      `${top.s} wins ${top.st.wins} of ${games.length} games with ${pct(topAi)} of its revenue from AI: AI's margin (${fmt(defaultConfig.rate.ai - defaultConfig.cost.ownPower, 1)} per MW against ${fmt(defaultConfig.rate.cloud - defaultConfig.cost.ownPower, 1)} for cloud) and its 6% growth decide bot-only games. ` +
        'That is the spec\'s margin table working as written, not a bot bug: a player who contests AI early (the 80% incumbent rule rewards being first) and buys back late can beat it.',
    )
  }
  out.push(nanFound ? 'NaN or Infinity found in a final state: a rule is broken.' : 'No NaN or Infinity in any final state.')
  return out
}

main()
