export type IconName = keyof typeof GRIDS

/** Merges horizontal runs of filled cells into rectangles: a short, crisp path per icon. */
function toPath(rows: string[]): string {
  let d = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x++
        continue
      }
      const start = x
      while (x < row.length && row[x] === '#') x++
      d += `M${start} ${y}h${x - start}v1h${start - x}z`
    }
  })
  return d
}

const PATHS = Object.fromEntries(Object.entries(GRIDS).map(([k, rows]) => [k, toPath(rows)])) as Record<IconName, string>

export const SEASON_ICONS: IconName[] = ['spring', 'summer', 'autumn', 'winter']

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName
  /** Pixel size; multiples of 16 keep every cell on the device grid. */
  size?: number
  /** When set the icon is announced; otherwise it is decorative. */
  title?: string
}

export function Icon({ name, size = 16, title, className, ...rest }: IconProps) {
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className ? `icon ${className}` : 'icon'}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      <path d={PATHS[name]} />
    </svg>
  )
}
