export type NetIconName = keyof typeof GRIDS

function toPath(rows: string[]): string {
  let d = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x++
        continue
      }
      const start = x
      while (x < row.length && row[x] === '#') x++
      d += `M${start} ${y}h${x - start}v1h${start - x}z`
    }
  })
  return d
}

const PATHS = Object.fromEntries(Object.entries(GRIDS).map(([k, rows]) => [k, toPath(rows)])) as Record<NetIconName, string>

export function NetIcon({ name, size = 16, className, ...rest }: Omit<SVGProps<SVGSVGElement>, 'name'> & { name: NetIconName; size?: number }) {
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className ? `icon ${className}` : 'icon'}
      aria-hidden
      focusable="false"
      {...rest}
    >
      <path d={PATHS[name]} />
    </svg>
  )
}
