#!/usr/bin/env node
/* tasu.ai app fonts. Run it from anywhere: node taste/_tools/fonts-apps.mjs
   The pages set each app's name, its 2 font specimens and its rebuilt UI elements in the closest
   free Google Font. This tool self-hosts those fonts: for each family it asks Google Fonts for
   exactly the glyphs the pages use (css2?family=...&text=...), saves the woff2 files under
   fonts/apps/ and writes fonts/apps.css (@font-face, font-display: swap). The pages never call a
   third party at runtime. Run it again after a change to an app name, a font or an element's
   text, then run build.mjs.
   Inputs: _data/selection.json, _data/raw/<slug>.json (name), _data/analysis/<slug>.json
   (branding.fonts), _data/elements/<slug>.json (fonts and text of each element). */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const TASTE = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(TASTE, '_data');
const OUT = join(TASTE, 'fonts', 'apps');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const read = f => (existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null);
const slugify = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Glyphs every subset carries, so a number or a punctuation mark never falls back.
const BASE = ' 0123456789.,:;%+-–/()&\'’"“”!?#$@AaBbCcDdEeFfGgHhIiJjKkLlMmNnOoPpQqRrSsTtUuVvWwXxYyZz';
// family -> { weights: Set, text: Set of chars }
const need = new Map();
const add = (family, weight, text) => {
  if (!family) return;
  const f = need.get(family) || { weights: new Set(), text: new Set(BASE) };
  f.weights.add(Number(weight) || 400);
  for (const ch of String(text)) f.text.add(ch);
  need.set(family, f);
};
const decode = s => s.replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#(\d+);/g, (m, n) => String.fromCodePoint(Number(n))).replace(/&#x([0-9a-f]+);/gi, (m, n) => String.fromCodePoint(parseInt(n, 16)));

const sel = read(join(DATA, 'selection.json'));
const slugs = sel?.apps?.map(a => a.slug) || readdirSync(join(DATA, 'raw')).map(f => f.replace(/\.json$/, ''));
for (const slug of slugs) {
  const raw = read(join(DATA, 'raw', `${slug}.json`));
  const an = read(join(DATA, 'analysis', `${slug}.json`)) || {};
  if (!raw) continue;
  const fonts = an.branding?.fonts || {};
  for (const role of ['headline', 'body']) {
    const f = fonts[role];
    if (!f?.closeTo) continue;
    // The card shows the font's name in the font; the specimen shows "Aa" and "<App> 0123456789".
    add(f.closeTo, f.weight, `${f.name || f.closeTo} Aa ${raw.name} 0123456789`);
    if (role === 'headline') add(f.closeTo, f.weight, raw.name); // the card's big name
  }
  const els = read(join(DATA, 'elements', `${slug}.json`));
  for (const el of els?.elements || []) {
    const text = decode(String(el.html || '').replace(/<[^>]+>/g, ' '));
    for (const f of el.fonts || []) add(f.family, f.weight, text);
  }
}

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (f.endsWith('.woff2')) rmSync(join(OUT, f));
const faces = [];
const problems = [];
for (const [family, { weights, text }] of [...need].sort((a, b) => a[0].localeCompare(b[0]))) {
  const glyphs = [...text].sort().join('');
  for (const w of [...weights].sort((a, b) => a - b)) {
    const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}:wght@${w}&text=${encodeURIComponent(glyphs)}&display=swap`;
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!res.ok) { problems.push(`${family} ${w}: Google Fonts answered ${res.status}`); continue; }
    const css = await res.text();
    const src = /src:\s*url\(([^)]+)\)\s*format\(['"]woff2['"]\)/.exec(css)?.[1];
    if (!src) { problems.push(`${family} ${w}: no woff2 in the answer`); continue; }
    const file = `${slugify(family)}-${w}.woff2`;
    const font = Buffer.from(await (await fetch(src, { headers: { 'User-Agent': UA } })).arrayBuffer());
    writeFileSync(join(OUT, file), font);
    faces.push(`@font-face {\n  font-family: "${family}";\n  font-style: normal;\n  font-weight: ${w};\n  font-display: swap;\n  src: url("apps/${file}") format("woff2");\n}`);
    console.log(`fonts/apps/${file} ${(font.length / 1024).toFixed(1)} KB, ${glyphs.length} glyphs`);
  }
}
writeFileSync(join(TASTE, 'fonts', 'apps.css'), `/* tasu.ai app fonts: the closest free Google Fonts of the 12 apps, cut to the glyphs the pages
   use. Generated by _tools/fonts-apps.mjs: do not edit by hand. Each family is under the
   SIL Open Font License; see fonts.google.com for each one. */
${faces.join('\n')}
`);
console.log(`fonts/apps.css: ${faces.length} faces, ${need.size} families`);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
